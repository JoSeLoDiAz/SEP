DECLARE
  PROCEDURE add_fk(p_ddl VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE p_ddl;
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -2264 AND SQLCODE != -2275 AND SQLCODE != -955 THEN RAISE; END IF;
  END;
BEGIN
  add_fk(q'[ALTER TABLE EVALUADORPARTICIPACION ADD CONSTRAINT FK_PART_CONVOCATORIA
    FOREIGN KEY (CONVOCATORIAID) REFERENCES EVALUADORCONVOCATORIA(CONVOCATORIAID)]');
  add_fk(q'[ALTER TABLE EVALUADORPARTICIPACION ADD CONSTRAINT FK_PART_ESTADO
    FOREIGN KEY (ESTADOPARTID) REFERENCES ESTADOPARTICIPACION(ESTADOPARTID)]');
  add_fk(q'[ALTER TABLE EVALUADORPARTICIPACION ADD CONSTRAINT FK_PART_AREA
    FOREIGN KEY (AREAID) REFERENCES AREAEVALUACION(AREAID)]');
  add_fk(q'[ALTER TABLE EVALUADORPARTICIPACION ADD CONSTRAINT FK_PART_MODALIDAD
    FOREIGN KEY (MODALIDADPARTID) REFERENCES MODALIDADPART(MODALIDADPARTID)]');

  add_fk(q'[ALTER TABLE EVALUADORPRUEBA ADD CONSTRAINT FK_PRUEBA_PART
    FOREIGN KEY (PARTICIPACIONID) REFERENCES EVALUADORPARTICIPACION(PARTICIPACIONID)]');

  add_fk(q'[ALTER TABLE EVALUADORDOCUMENTO ADD CONSTRAINT FK_EVALDOC_PART
    FOREIGN KEY (PARTICIPACIONID) REFERENCES EVALUADORPARTICIPACION(PARTICIPACIONID)]');

  add_fk(q'[ALTER TABLE EVALUADORCONVOCATORIA ADD CONSTRAINT FK_CONV_MODALIDAD
    FOREIGN KEY (MODALIDADPARTID) REFERENCES MODALIDADPART(MODALIDADPARTID)]');
END;
/

