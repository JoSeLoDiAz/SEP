-- v34_evaluador_participacion_spine.sql
-- ──────────────────────────────────────────────────────────────────────────
-- Convierte EVALUADORPARTICIPACION en la COLUMNA VERTEBRAL del ciclo anual.
--
-- Hasta ahora participaciones, pruebas, documentos y convocatorias eran
-- cuatro islas que solo compartían un NUMBER(4) con el año. Esta migración
-- las ata:
--
--   EVALUADORPARTICIPACION  + CONVOCATORIAID, ESTADOPARTID, AREAID,
--                             MODALIDADPARTID, ESTRANSVERSAL, fechas, motivo
--   EVALUADORPRUEBA         + PARTICIPACIONID, APROBADA, PUNTAJEMINIMO
--   EVALUADORDOCUMENTO      + PARTICIPACIONID
--   EVALUADORCONVOCATORIA   + CONVOCATORIASEPID, notas de corte, MODALIDADPARTID
--
-- Y agrega dos tablas hijas que vienen del módulo de retroalimentación:
--   EVALUADORPARTGRUPO    — grupos (mesas) 1..8 en que participa ese año
--   EVALUADORPARTALCANCE  — alcance explícito de un evaluador transversal
--
-- Los PARTICIPACIONID nuevos son NULLABLE a propósito: el histórico 2021-2023
-- (pruebas sueltas, documentos sin ciclo) entra sin bloqueo y se ata después.
--
-- Idempotente. Ejecutar como SEPLOCAL, DESPUÉS de la v29.
-- ──────────────────────────────────────────────────────────────────────────


-- ╔════════════════════════════════════════════════════════════════════════╗
-- ║ 1. EVALUADORPARTICIPACION — columnas del ciclo                          ║
-- ╚════════════════════════════════════════════════════════════════════════╝

DECLARE
  PROCEDURE add_col(p_tabla VARCHAR2, p_ddl VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE ' || p_tabla || ' ADD (' || p_ddl || ')';
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -1430 THEN RAISE; END IF;
  END;
BEGIN
  add_col('EVALUADORPARTICIPACION', 'CONVOCATORIAID NUMBER(10)');
  add_col('EVALUADORPARTICIPACION', 'ESTADOPARTID NUMBER(10)');
  add_col('EVALUADORPARTICIPACION', 'AREAID NUMBER(10)');
  add_col('EVALUADORPARTICIPACION', 'MODALIDADPARTID NUMBER(10)');
  add_col('EVALUADORPARTICIPACION', 'ESTRANSVERSAL NUMBER(1) DEFAULT 0');
  add_col('EVALUADORPARTICIPACION', 'MOTIVONOPARTICIPA NVARCHAR2(300)');
  add_col('EVALUADORPARTICIPACION', 'FECHAINICIO DATE');
  add_col('EVALUADORPARTICIPACION', 'FECHAFIN DATE');
  add_col('EVALUADORPARTICIPACION', 'USUARIOCREACION NVARCHAR2(200)');
  add_col('EVALUADORPARTICIPACION', 'FECHACREACION DATE DEFAULT SYSDATE');
  add_col('EVALUADORPARTICIPACION', 'USUARIOMODIFICACION NVARCHAR2(200)');
  add_col('EVALUADORPARTICIPACION', 'FECHAMODIFICACION DATE');

  add_col('EVALUADORPRUEBA', 'PARTICIPACIONID NUMBER(10)');
  add_col('EVALUADORPRUEBA', 'APROBADA NUMBER(1)');
  add_col('EVALUADORPRUEBA', 'PUNTAJEMINIMO NUMBER(5,2)');
  add_col('EVALUADORPRUEBA', 'USUARIOCREACION NVARCHAR2(200)');
  add_col('EVALUADORPRUEBA', 'FECHACREACION DATE DEFAULT SYSDATE');

  add_col('EVALUADORDOCUMENTO', 'PARTICIPACIONID NUMBER(10)');
  add_col('EVALUADORDOCUMENTO', 'USUARIOCREACION NVARCHAR2(200)');

  add_col('EVALUADORCONVOCATORIA', 'CONVOCATORIASEPID NUMBER(10)');
  add_col('EVALUADORCONVOCATORIA', 'MODALIDADPARTID NUMBER(10)');
  add_col('EVALUADORCONVOCATORIA', 'PUNTAJEMINIMOPRUEBA NUMBER(5,2)');
  add_col('EVALUADORCONVOCATORIA', 'CALIFICACIONMINIMACURSO NUMBER(5,2)');
  add_col('EVALUADORCONVOCATORIA', 'USUARIOCREACION NVARCHAR2(200)');
  add_col('EVALUADORCONVOCATORIA', 'USUARIOMODIFICACION NVARCHAR2(200)');
  add_col('EVALUADORCONVOCATORIA', 'FECHAMODIFICACION DATE');
END;
/

COMMENT ON COLUMN EVALUADORPARTICIPACION.CONVOCATORIAID IS
  'Ciclo del banco al que pertenece. Habilita heredar los documentos generales del año sin duplicarlos por evaluador.';
COMMENT ON COLUMN EVALUADORPARTICIPACION.ESTADOPARTID IS
  'Estado declarado del ciclo. El backend calcula además un estadoSugerido desde el checklist y avisa si divergen.';
COMMENT ON COLUMN EVALUADORPARTICIPACION.AREAID IS
  'Área (Técnica/Jurídica/Financiera) en la que actuó ESE año. Es contexto anual, no atributo de la persona.';
COMMENT ON COLUMN EVALUADORPARTICIPACION.ESTRANSVERSAL IS
  '1 = evaluó con alcance explícito multi-área (ver EVALUADORPARTALCANCE), no por su grupo.';
COMMENT ON COLUMN EVALUADORPARTICIPACION.MOTIVONOPARTICIPA IS
  'Por qué declinó / no aprobó / se le revocó. Obligatorio en aplicación cuando el estado es ESNEGATIVO = 1.';

COMMENT ON COLUMN EVALUADORPRUEBA.PARTICIPACIONID IS
  'Ciclo al que corresponde la prueba. NULL = histórico suelto (2021-2023) que todavía no se ató a una participación.';
COMMENT ON COLUMN EVALUADORPRUEBA.PUNTAJEMINIMO IS
  'Nota de corte vigente al presentar. Congelada para que un cambio posterior no reescriba el histórico.';

COMMENT ON COLUMN EVALUADORDOCUMENTO.PARTICIPACIONID IS
  'NULL = documento personal permanente (cédula, HV). No nulo = documento propio de ese ciclo.';

COMMENT ON COLUMN EVALUADORCONVOCATORIA.CONVOCATORIASEPID IS
  'FK lógica a la CONVOCATORIA real del SEP (la de proyectos). Nullable: un ciclo del banco puede no mapear 1:1.';
COMMENT ON COLUMN EVALUADORCONVOCATORIA.PUNTAJEMINIMOPRUEBA IS
  'Nota de corte de la prueba de conocimiento de ESE año. Cambia año a año.';


