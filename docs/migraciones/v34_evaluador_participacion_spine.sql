-- ╔════════════════════════════════════════════════════════════════════════╗
-- ║ 3. EVALUADORPARTGRUPO — grupos/mesas del año (N:M)                      ║
-- ╚════════════════════════════════════════════════════════════════════════╝
-- Viene de EvalPersona.grupos [1..8]. Una persona puede estar en varios
-- grupos el mismo año (ej. un apoyo jurídico en los grupos 1, 2 y 8), por eso
-- es tabla y no columna.

BEGIN
  EXECUTE IMMEDIATE q'[CREATE TABLE EVALUADORPARTGRUPO (
    PARTGRUPOID      NUMBER(10)   NOT NULL,
    PARTICIPACIONID  NUMBER(10)   NOT NULL,
    GRUPONUMERO      NUMBER(3)    NOT NULL,
    ESPRINCIPAL      NUMBER(1)    DEFAULT 0 NOT NULL,
    CONSTRAINT PK_EVALUADORPARTGRUPO PRIMARY KEY (PARTGRUPOID),
    CONSTRAINT UQ_PARTGRUPO UNIQUE (PARTICIPACIONID, GRUPONUMERO),
    CONSTRAINT FK_PARTGRUPO_PART FOREIGN KEY (PARTICIPACIONID)
      REFERENCES EVALUADORPARTICIPACION(PARTICIPACIONID)
  )]';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

COMMENT ON TABLE EVALUADORPARTGRUPO IS
  'Grupos (mesas) en que participó el evaluador ese año. Alimenta el generador de la matriz de retroalimentación.';

BEGIN
  EXECUTE IMMEDIATE 'CREATE SEQUENCE EVALUADORPARTGRUPO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IX_PARTGRUPO_GRUPO ON EVALUADORPARTGRUPO (GRUPONUMERO)';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 AND SQLCODE != -1408 THEN RAISE; END IF;
