-- PASO 3f (v71) — las 9 llaves foraneas hacia las tablas que ya existian.
--
-- Es el bloque 5 de la v69, separado en su propio archivo. Los bloques 1 a 4 de
-- la v69 ya estan aplicados; correr aquel archivo entero volveria a fallar en los
-- CREATE TABLE. Este se corre solo.
--
-- POR QUE HASTA AHORA
-- Estas llaves apuntan a CIUDAD, CONVOCATORIA, PERSONA, PROYECTO, PERFIL y
-- USUARIO. Las filas padre que faltaban ya entraron en los pasos 3b, 3d y
-- 3f-previo: 24 PERSONA, 82 USUARIO, 1 PERFIL, 5 CONVOCATORIA, 2 EMPRESA y
-- 2 PROYECTO. El mapa de traduccion de ids esta en respaldos/, fuera del repo.
--
-- POR QUE VA ANTES DEL PASO 4 Y NO DESPUES
-- Las 9 tablas hijas estan VACIAS: crear la llave ahora no valida ninguna fila y
-- es instantaneo. Y a partir de aqui la base misma vigila el paso 4 — si un id
-- quedara mal traducido, el INSERT muere con ORA-02291 en vez de dejar una fila
-- huerfana que nadie note.
--
-- ESTO ES DDL: cada ALTER confirma solo. No hay transaccion ni ROLLBACK posible.
-- Por eso va WHENEVER SQLERROR EXIT FAILURE: si una falla, para ahi mismo y las
-- anteriores quedan creadas. No es grave — no se toca ni una fila — y la reversa
-- del final las quita.
--
-- COMPROBADO CONTRA EL EXADATA ANTES DE GENERAR ESTO
--   · Las 9 tablas hijas existen y tienen 0 filas.
--   · Las 9 columnas hijas existen.
--   · Ninguna de las 9 llaves existe todavia.
--   · Las columnas de la clave primaria del padre se leyeron del diccionario del
--     Exadata, no de un mapa. La primera version salio con REFERENCES "CIUDAD" ()
--     y murio con ORA-00936 justo por eso.
--
-- Correr como SENADM, con F5.

WHENEVER SQLERROR EXIT FAILURE;
SET DEFINE OFF;
SET SERVEROUTPUT ON;

-- ==================== GUARDAS ====================
DECLARE
  v_base VARCHAR2(128); v_n NUMBER;
BEGIN
  SELECT SYS_CONTEXT('USERENV','DB_NAME') INTO v_base FROM dual;
  IF v_base <> 'PDB_SEPDB' THEN
    RAISE_APPLICATION_ERROR(-20001, 'BASE EQUIVOCADA: estas en ' || v_base);
  END IF;

  -- ninguna de las 9 llaves puede existir ya
  SELECT COUNT(*) INTO v_n FROM ALL_CONSTRAINTS
   WHERE OWNER='SENADM' AND CONSTRAINT_NAME IN (
     'FK_CF_CIUDAD',
     'FK_EVALCONV_CONVSEP',
     'FK_EVALUADOR_MUNICIPIO',
     'FK_EVALUADOR_PERSONA',
     'FK_PART_DINAMIZADOR',
     'FK_PROYECTOAPROBADO_PROY',
     'FK_PROYECTOVERSION_PROYECTO',
     'FK_USUARIOPERFIL_PERFIL',
     'FK_USUARIOPERFIL_USUARIO');
  IF v_n <> 0 THEN
    RAISE_APPLICATION_ERROR(-20002, 'Ya existen ' || v_n || ' de las 9 llaves. Esto ya se corrio.');
  END IF;

  -- las filas padre del 3f-previo tienen que estar
  SELECT COUNT(*) INTO v_n FROM SENADM.CONVOCATORIA WHERE "CONVOCATORIAID" BETWEEN 10 AND 14;
  IF v_n <> 5 THEN
    RAISE_APPLICATION_ERROR(-20003, 'Faltan convocatorias del 3f-previo: hay ' || v_n || ' de 5.');
  END IF;
  SELECT COUNT(*) INTO v_n FROM SENADM.PROYECTO WHERE "PROYECTOID" IN (3049, 3050);
  IF v_n <> 2 THEN
    RAISE_APPLICATION_ERROR(-20004, 'Faltan los 2 proyectos del 3f-previo: hay ' || v_n || ' de 2.');
  END IF;

  DBMS_OUTPUT.PUT_LINE('Base ' || v_base
    || ' — 0 de las 9 llaves creadas, filas padre presentes. Adelante.');
END;
