-- ==================== COMPROBACION ====================
-- Tienen que salir las 9, todas ENABLED y VALIDATED.
SELECT c.CONSTRAINT_NAME, c.TABLE_NAME AS HIJA, cc.COLUMN_NAME AS COLUMNA,
       rc.TABLE_NAME AS PADRE, c.STATUS, c.VALIDATED
  FROM ALL_CONSTRAINTS c
  JOIN ALL_CONS_COLUMNS cc ON cc.OWNER=c.OWNER AND cc.CONSTRAINT_NAME=c.CONSTRAINT_NAME
  JOIN ALL_CONSTRAINTS rc ON rc.OWNER=c.R_OWNER AND rc.CONSTRAINT_NAME=c.R_CONSTRAINT_NAME
 WHERE c.OWNER='SENADM' AND c.CONSTRAINT_NAME IN (
   'FK_CF_CIUDAD',
   'FK_EVALCONV_CONVSEP',
   'FK_EVALUADOR_MUNICIPIO',
   'FK_EVALUADOR_PERSONA',
   'FK_PART_DINAMIZADOR',
   'FK_PROYECTOAPROBADO_PROY',
   'FK_PROYECTOVERSION_PROYECTO',
   'FK_USUARIOPERFIL_PERFIL',
   'FK_USUARIOPERFIL_USUARIO')
 ORDER BY c.TABLE_NAME, c.CONSTRAINT_NAME;

